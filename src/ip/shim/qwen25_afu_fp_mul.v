// ===========================================================================
// qwen25_afu_fp_mul -- hardware implementation of the FP32 multiply core.
//
// Replaces  models\qwen25_scalar_math_verilator.sv :: qwen25_afu_fp_mul
//          (newdma\work_afu\sim_ip_models.sv :: qwen25_afu_fp_mul)
// Port list is identical to the behavioural model, so no caller changes.
//
// Backing IP : xilinx.com:ip:floating_point:7.1  (ip_fp_mul)
//   Operation_Type Multiply / Single / NonBlocking / no result tready
//   C_Latency = 3   (matches qwen_operator_valid_guard #(.C_LATENCY(3)) at
//                    rtl\afu\qwen25_afu_lane.v:50, rtl\rope\qwen25_rope.v:166,
//                    rtl\rope\qwen25_rope_vector.v:132)
//
// Why a shim and not a direct instantiation: the Floating-Point 7.1 IP
// generated by Vivado 2026.1 has no result-side TUSER (only A/B/C input TUSER
// exist), while the model propagates a 16-bit A TUSER with the same latency as
// the result.  The shim adds that passthrough with a matching 3-deep pipeline.
// The arithmetic is done entirely by the vendor core.
// ===========================================================================
module qwen25_afu_fp_mul (
    input  wire        aclk,
    input  wire        s_axis_a_tvalid, input wire [31:0] s_axis_a_tdata,
    input  wire [15:0] s_axis_a_tuser,
    input  wire        s_axis_b_tvalid, input wire [31:0] s_axis_b_tdata,
    output wire        m_axis_result_tvalid, output wire [31:0] m_axis_result_tdata,
    output wire [15:0] m_axis_result_tuser
);
    // ------------------------------------------------------------------ core
    ip_fp_mul core (
        .aclk                (aclk),
        .s_axis_a_tvalid     (s_axis_a_tvalid),
        .s_axis_a_tdata      (s_axis_a_tdata),
        .s_axis_b_tvalid     (s_axis_b_tvalid),
        .s_axis_b_tdata      (s_axis_b_tdata),
        .m_axis_result_tvalid(m_axis_result_tvalid),
        .m_axis_result_tdata (m_axis_result_tdata)
    );

    // ------------------------------------------- A TUSER passthrough (16 bit)
    // Same depth and shift behaviour as the model's user_pipe: shifts every
    // clock, so stage 2 is the TUSER that was presented when the result
    // currently leaving the core was accepted.
    localparam integer C_LATENCY = 3;
    reg [15:0] user_pipe [0:C_LATENCY-1];
    integer stage;
    always @(posedge aclk) begin
        user_pipe[0] <= s_axis_a_tuser;
        for (stage = 1; stage < C_LATENCY; stage = stage + 1)
            user_pipe[stage] <= user_pipe[stage-1];
    end
    assign m_axis_result_tuser = user_pipe[C_LATENCY-1];
endmodule
`default_nettype wire
